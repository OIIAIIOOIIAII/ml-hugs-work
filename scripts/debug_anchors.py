def project_points_to_image(points, camera):
    pts = torch.as_tensor(points, dtype=torch.float32, device=camera["world_view_transform"].device)
    ones = torch.ones((pts.shape[0], 1), dtype=pts.dtype, device=pts.device)
    pts_h = torch.cat([pts, ones], dim=1)
    clip = pts_h @ camera["full_proj_transform"]
    ndc = clip[:, :3] / clip[:, 3:4].clamp(min=1e-6)
    width = float(camera["image_width"])
    height = float(camera["image_height"])
    x = (ndc[:, 0] + 1.0) * 0.5 * width
    y = (ndc[:, 1] + 1.0) * 0.5 * height
    return torch.stack([x, y, ndc[:, 2]], dim=1)


def draw_overlay_on_render(image_tensor, camera, anchors, bindings, mu_canon, out_path, local_mask=None):
    from PIL import Image, ImageDraw, ImageFont

    image = (image_tensor.detach().cpu().permute(1, 2, 0).numpy().clip(0, 1) * 255).astype(np.uint8)
    pil = Image.fromarray(image)
    draw = ImageDraw.Draw(pil, "RGBA")
    font = ImageFont.load_default()

    mu_2d = project_points_to_image(mu_canon, camera).detach().cpu().numpy()
    anchor_2d = project_points_to_image(anchors["pos_canon"], camera).detach().cpu().numpy()
    normal_end = anchors["pos_canon"] + anchors["normal_canon"] * 0.12
    normal_2d = project_points_to_image(normal_end, camera).detach().cpu().numpy()

    top_ids = bindings["top1_anchor_id"].detach().cpu().numpy()
    if local_mask is None:
        local_mask_np = np.ones(top_ids.shape[0], dtype=bool)
    else:
        local_mask_np = local_mask.detach().cpu().numpy().astype(bool)

    height, width = image.shape[:2]
    for anchor_id, name in enumerate(anchors["names"]):
        color = tuple(get_anchor_color(name, anchor_id).tolist())
        mask = (top_ids == anchor_id) & local_mask_np
        pts = mu_2d[mask]
        pts = pts[(pts[:, 0] >= 0) & (pts[:, 0] < width) & (pts[:, 1] >= 0) & (pts[:, 1] < height)]
        for x, y, _ in pts[:: max(1, len(pts) // 350)]:
            draw.ellipse((x - 1.5, y - 1.5, x + 1.5, y + 1.5), fill=color + (185,))

        ax, ay, _ = anchor_2d[anchor_id]
        nx, ny, _ = normal_2d[anchor_id]
        if 0 <= ax < width and 0 <= ay < height:
            r = 7
            draw.ellipse((ax - r, ay - r, ax + r, ay + r), fill=color + (255,), outline=(0, 0, 0, 255), width=2)
            draw.line((ax, ay, nx, ny), fill=(0, 0, 0, 255), width=2)
            draw.ellipse((nx - 3, ny - 3, nx + 3, ny + 3), fill=(255, 214, 64, 255))
            draw.text((ax + r + 3, ay - r), name, fill=(0, 0, 0, 245), font=font)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    pil.save(out_path)


def run_raster_overlay(args):
    from hugs.datasets.utils import get_rotating_camera
    from hugs.renderer.gs_renderer import render
    from hugs.utils.rotations import matrix_to_quaternion, rotation_6d_to_matrix
    from hugs.models.hugs_trimlp import HUGS_TRIMLP

    out_dir = make_anchor_debug_dir(args.output_dir, "expC_raster_overlay")
    anchor_vertices_path = args.anchor_vertices or "output/anchor_debug/expA_template/anchor_vertices.json"
    anchor_vertices = load_anchor_vertices(anchor_vertices_path)

    device = "cuda"
    model = HUGS_TRIMLP(sh_degree=3, n_subdivision=args.n_subdivision, betas=torch.zeros(10, device=device))
    init_vals = model.initialize()
    mu = model.get_xyz.detach()
    template = make_template_from_vertices(
        model.get_vitruvian_verts_template(),
        model.smpl_template.faces,
        model.smpl_template.lbs_weights,
        canonical_pose="hugs_vitruvian",
    )
    anchors = compute_anchors(template, anchor_vertices)
    bindings = bind_gaussians_to_anchors(
        mu.detach().cpu(),
        init_vals["lbs_weights"].detach().cpu(),
        anchors,
        top_m=args.top_m,
        lambda_lbs=args.lambda_lbs,
        sigma_scale=args.sigma_scale,
        min_sigma=args.min_sigma,
    )
    local_mask = compute_binding_local_mask(bindings, vis_radius_factor=args.vis_radius_factor)
    scales = init_vals["scales"].detach()
    rotq = matrix_to_quaternion(rotation_6d_to_matrix(init_vals["rot6d_canon"].detach()))
    opacity = init_vals["opacity"].detach().clamp(min=0.18)

    top_ids = bindings["top1_anchor_id"].to(device)
    local_mask_dev = local_mask.to(device)
    rgb = torch.full((mu.shape[0], 3), 0.72, dtype=torch.float32, device=device)
    for idx, name in enumerate(anchors["names"]):
        color = torch.tensor(get_anchor_color(name, idx), dtype=torch.float32, device=device) / 255.0
        rgb[(top_ids == idx) & local_mask_dev] = color

    cameras = get_rotating_camera(img_size=args.image_size, fov=0.4, dist=5.0, device=device, nframes=args.overlay_frames)
    bg = torch.ones(3, dtype=torch.float32, device=device)
    outputs = []
    for frame_id, cam in enumerate(cameras):
        pkg = render(
            means3D=mu,
            feats=rgb,
            opacity=opacity,
            scales=scales,
            rotations=rotq,
            data=cam,
            scaling_modifier=1.0,
            bg_color=bg,
            active_sh_degree=0,
        )
        raw_path = out_dir / f"raster_anchor_binding_frame{frame_id:03d}.png"
        overlay_path = out_dir / f"raster_anchor_binding_frame{frame_id:03d}_overlay.png"
        from PIL import Image
        raw = (pkg["render"].detach().cpu().permute(1, 2, 0).numpy().clip(0, 1) * 255).astype(np.uint8)
        Image.fromarray(raw).save(raw_path)
        draw_overlay_on_render(pkg["render"], cam, anchors, bindings, mu.detach().cpu(), overlay_path, local_mask=local_mask)
        outputs.extend([raw_path, overlay_path])

    print(f"Raster overlay outputs written to: {out_dir}")
    for path in outputs:
        print(f"- {relative_to_cwd(path)}")


