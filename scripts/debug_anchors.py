def simulate_inheritance_step(mu, anchor_ids, anchor_weights, anchors, rng, clone_frac, split_frac, prune_frac):
    bindings = make_binding_dict_from_inherited(anchor_ids, anchor_weights, anchors, mu)
    local_mask = compute_binding_local_mask(bindings, vis_radius_factor=1.35).to(mu.device)

    n_points = mu.shape[0]
    local_idx = torch.where(local_mask)[0]
    if local_idx.numel() == 0:
        local_idx = torch.arange(n_points, device=mu.device)

    clone_count = min(max(1, int(n_points * clone_frac)), local_idx.numel())
    clone_parent = local_idx[torch.as_tensor(rng.permutation(local_idx.numel())[:clone_count], device=mu.device)]
    clone_noise = torch.from_numpy(rng.normal(0.0, 0.006, size=(clone_count, 3))).to(mu.device).float()
    clone_mu = mu[clone_parent] + clone_noise
    clone_ids = anchor_ids[clone_parent].clone()
    clone_weights = anchor_weights[clone_parent].clone()

    split_count = min(max(1, int(n_points * split_frac)), local_idx.numel())
    split_parent = local_idx[torch.as_tensor(rng.permutation(local_idx.numel())[:split_count], device=mu.device)]
    split_children = 2
    split_noise = torch.from_numpy(rng.normal(0.0, 0.014, size=(split_count * split_children, 3))).to(mu.device).float()
    split_mu = mu[split_parent].repeat(split_children, 1) + split_noise
    split_ids = anchor_ids[split_parent].repeat(split_children, 1).clone()
    split_weights = anchor_weights[split_parent].repeat(split_children, 1).clone()

    keep = torch.ones(n_points, dtype=torch.bool, device=mu.device)
    keep[split_parent] = False
    prune_candidates = torch.where((~local_mask) & keep)[0]
    prune_count = min(int(n_points * prune_frac), prune_candidates.numel())
    if prune_count > 0:
        prune_idx = prune_candidates[
            torch.as_tensor(rng.permutation(prune_candidates.numel())[:prune_count], device=mu.device)
        ]
        keep[prune_idx] = False

    next_mu = torch.cat([mu[keep], clone_mu, split_mu], dim=0)
    next_ids = torch.cat([anchor_ids[keep], clone_ids, split_ids], dim=0)
    next_weights = torch.cat([anchor_weights[keep], clone_weights, split_weights], dim=0)
    return next_mu, next_ids, next_weights


