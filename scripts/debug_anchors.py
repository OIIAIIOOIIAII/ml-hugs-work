def make_binding_dict_from_inherited(anchor_ids, anchor_weights, anchors, mu):
    anchor_pos = anchors["pos_canon"].to(mu.device)
    top_ids = anchor_ids[:, 0]
    top_dist = torch.linalg.norm(mu - anchor_pos[top_ids], dim=1)
    sigma = torch.clamp(anchors["radius"].to(mu.device) * 1.8, min=0.035)
    return {
        "gaussian_anchor_ids": anchor_ids.cpu(),
        "gaussian_anchor_weights": anchor_weights.cpu(),
        "top1_anchor_id": top_ids.cpu(),
        "top1_anchor_dist": top_dist.cpu(),
        "sigma": sigma.cpu(),
    }


def write_anchor_stats_csv(path, iter_id, bindings, anchors, local_mask):
    path.parent.mkdir(parents=True, exist_ok=True)
    top_ids = bindings["top1_anchor_id"]
    top_dist = bindings["top1_anchor_dist"]
    top_weight = bindings["gaussian_anchor_weights"][:, 0]
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([
            "iter",
            "anchor_name",
            "num_gaussians",
            "num_local_gaussians",
            "mean_dist_to_anchor_canon",
            "max_dist_to_anchor_canon",
            "mean_assignment_weight",
        ])
        for anchor_id, name in enumerate(anchors["names"]):
            mask = top_ids == anchor_id
            local = mask & local_mask
            if mask.any():
                writer.writerow([
                    iter_id,
                    name,
                    int(mask.sum()),
                    int(local.sum()),
                    float(top_dist[mask].mean()),
                    float(top_dist[mask].max()),
                    float(top_weight[mask].mean()),
                ])
            else:
                writer.writerow([iter_id, name, 0, 0, "", "", ""])


