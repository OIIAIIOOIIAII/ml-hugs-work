def render_stats_heatmap(path, rows, metric_names):
    from PIL import Image, ImageDraw, ImageFont

    names = [r["anchor_name"] for r in rows]
    values = np.array([[float(r[m]) for m in metric_names] for r in rows], dtype=np.float32)
    finite = np.isfinite(values)
    norm = np.zeros_like(values, dtype=np.float32)
    for j in range(values.shape[1]):
        col = values[:, j]
        mask = finite[:, j]
        if mask.any():
            vmin, vmax = np.nanmin(col), np.nanmax(col)
            norm[:, j] = 0.5 if abs(vmax - vmin) < 1e-8 else (col - vmin) / (vmax - vmin)

    cell_w, cell_h = 86, 28
    left_w, top_h = 145, 120
    width = left_w + cell_w * len(metric_names)
    height = top_h + cell_h * len(names)
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    font = ImageFont.load_default()

    for j, metric in enumerate(metric_names):
        x = left_w + j * cell_w + 4
        draw.text((x, 8), metric.replace("_", "\n"), fill=(0, 0, 0), font=font)
    for i, name in enumerate(names):
        y = top_h + i * cell_h
        draw.text((8, y + 8), name, fill=(0, 0, 0), font=font)
        for j in range(len(metric_names)):
            t = float(norm[i, j])
            if not finite[i, j]:
                color = (230, 230, 230)
                text = "nan"
            else:
                color = (int(255 * t), int(170 * (1 - abs(t - 0.5) * 2)), int(255 * (1 - t)))
                text = f"{values[i, j]:.3g}"
            x = left_w + j * cell_w
            draw.rectangle((x, y, x + cell_w - 1, y + cell_h - 1), fill=color, outline=(255, 255, 255))
            draw.text((x + 4, y + 8), text, fill=(0, 0, 0), font=font)
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


def render_matrix_heatmap(path, matrix, row_names, col_names, title):
    from PIL import Image, ImageDraw, ImageFont

    matrix = np.asarray(matrix, dtype=np.float32)
    cell_w, cell_h = 34, 26
    left_w, top_h = 150, 70
    width = left_w + cell_w * len(col_names)
    height = top_h + cell_h * len(row_names)
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    font = ImageFont.load_default()
    draw.text((8, 8), title, fill=(0, 0, 0), font=font)
    vmin, vmax = np.nanmin(matrix), np.nanmax(matrix)
    denom = max(float(vmax - vmin), 1e-8)
    for j, name in enumerate(col_names):
        draw.text((left_w + j * cell_w + 2, 38), str(name)[:4], fill=(0, 0, 0), font=font)
    for i, name in enumerate(row_names):
        y = top_h + i * cell_h
        draw.text((8, y + 8), name, fill=(0, 0, 0), font=font)
        for j in range(len(col_names)):
            t = (matrix[i, j] - vmin) / denom
            color = (int(255 * t), int(80 + 120 * (1 - abs(t - 0.5) * 2)), int(255 * (1 - t)))
            x = left_w + j * cell_w
            draw.rectangle((x, y, x + cell_w - 1, y + cell_h - 1), fill=color, outline=(255, 255, 255))
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


def render_token_scatter(path, tokens, names, title):
    from PIL import Image, ImageDraw, ImageFont

    x = np.asarray(tokens, dtype=np.float32)
    x = x - x.mean(axis=0, keepdims=True)
    _, _, vt = np.linalg.svd(x, full_matrices=False)
    pts = x @ vt[:2].T
    mins, maxs = pts.min(axis=0), pts.max(axis=0)
    pts = (pts - mins[None]) / np.maximum(maxs - mins, 1e-8)
    size = 900
    image = Image.new("RGB", (size, size), "white")
    draw = ImageDraw.Draw(image, "RGBA")
    font = ImageFont.load_default()
    draw.text((15, 12), title, fill=(0, 0, 0, 255), font=font)
    for idx, name in enumerate(names):
        px = 80 + pts[idx, 0] * (size - 160)
        py = 80 + (1.0 - pts[idx, 1]) * (size - 160)
        color = tuple(get_anchor_color(name, idx).tolist()) + (255,)
        draw.ellipse((px - 8, py - 8, px + 8, py + 8), fill=color, outline=(0, 0, 0, 255), width=2)
        draw.text((px + 10, py - 6), name, fill=(0, 0, 0, 235), font=font)
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


