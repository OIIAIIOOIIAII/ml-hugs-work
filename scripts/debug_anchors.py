def run_template(args):
    out_dir = make_anchor_debug_dir(args.output_dir, "expA_template")
    template = load_smpl_template(args.smpl_model_path)

    if args.anchor_vertices:
        anchor_vertices = load_anchor_vertices(args.anchor_vertices)
    else:
        anchor_vertices = generate_semantic_anchor_vertices(
            template,
            count_per_anchor=args.count_per_anchor,
        )

    anchors = compute_anchors(template, anchor_vertices)

    anchor_vertices_path = out_dir / "anchor_vertices.json"
    anchors_pt_path = out_dir / "anchors.pt"
    anchors_csv_path = out_dir / "anchors.csv"
    mesh_path = out_dir / "template_mesh_anchor_regions.ply"
